"""server/worldd/combat/npc_kits.h: what the retail NPCs fight with (plan E1, stage 3).

The abilities each creature kind uses against a player, from the retail captures as the combat research read them (research/combat/picks.json, tables
npc_kits, type_stats_onme, ability_windup): for every Blueprint class the captures opened, the abilities of its open's AbilityComponent
(ReplicatedRecordsToLoad) with how often the captures saw each one cast on a player, how long after the cast the hit confirmation came (the windup), and how far
from the player the NPC was at the cast (the range it fights at).  The AI (npc/ai/npc_ai.h) picks among them by their weights; a kind the captures did not
open fights with a level-scaled generic slash.

    python tools/capture/gen_npc_kits.py --picks PATH            # rewrite the header from the research's picks.json
    python tools/capture/gen_npc_kits.py --picks PATH --check    # write nothing, exit 1 on a change

PATH is research/combat/picks.json of the stage 3 research folder (it is not in the repository; AOC_COMBAT_PICKS names it too).
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'server', 'world', 'combat', 'npc_kits.h')

DEFAULT_WINDUP_MS = 500      # an ability with no measured windup
DEFAULT_RANGE_CM = 250       # and no measured range


def _ability_ranges(ty):
    if not ty:
        return {}, 0
    interval = int(ty['interval'][1]) if ty.get('interval') else 0
    per_ability = {}
    for a in ty.get('abilities', []):
        ranges = [int(r[1]) for r in a.get('static', {}).get('range', [])]
        rng = max(ranges, default=0)
        if rng == 0 and a.get('dist'):
            rng = int(a['dist'][1])
        per_ability[a['ability']] = rng
    return per_ability, interval


def kits_of(picks):
    tables = picks['tables']
    kits = tables['npc_kits']
    windup = tables.get('ability_windup', {})
    typed = tables.get('type_stats_onme', {})
    # type_stats_onme is keyed by the family ("Rabid"), npc_kits by the Blueprint class ("Rabid_C", "Bandit_Raider_Dunir_C")
    out = {}
    for cls, kit in sorted(kits.items()):
        leaf = cls[:-2] if cls.endswith('_C') else cls
        ty = next((typed[f] for f in (leaf, leaf.split('_')[0], '_'.join(leaf.split('_')[:2])) if f in typed), None)
        per_ability, interval = _ability_ranges(ty)
        abilities = []
        for name, n in kit['abilities']:
            w = windup.get(name)
            wu = int(w['dt'][1]) if (w and w.get('dt') and w['dt'][1] > 0) else DEFAULT_WINDUP_MS
            abilities.append((name, int(n), wu, per_ability.get(name, 0) or DEFAULT_RANGE_CM))
        abilities.sort(key=lambda a: (-a[1], a[0]))
        out[leaf] = (abilities, interval)
    return out


def kits_from_header():
    combat_dir = os.path.dirname(OUT)
    parts = [os.path.join(combat_dir, n) for n in ('npc_kits_a.h', 'npc_kits_b.h', 'npc_kits.h')]
    raw = '\n'.join(open(p, encoding='utf-8').read() for p in parts if os.path.exists(p))
    ab_re = re.compile(r'inline constexpr KitAbility kAbilities(\d+)\[\]\s*=\s*\{(.*?)\};', re.DOTALL)
    entry_re = re.compile(r'\{"([^"]+)",\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\}')
    ab_map = {
        int(m.group(1)): [(n, int(u), int(w), int(r)) for n, u, w, r in entry_re.findall(m.group(2))]
        for m in ab_re.finditer(raw)
    }
    kit_re = re.compile(r'\{"([^"]+)",\s*kAbilities(\d+),\s*\d+,\s*(-?\d+)\}')
    return {m.group(1): (ab_map[int(m.group(2))], int(m.group(3))) for m in kit_re.finditer(raw)}


# C-O-A + Cyb

def render(kits):
    lines = [
        '// SPDX-License-Identifier: AGPL-3.0-only',
        '// Copyright (C) 2026 Cyb and contributors. Developed by Cyb; thanks to Hatemost and CoA (Creation of Ashes).',
        '// GNU AGPL v3 with additional terms under section 7: see LICENSE and NOTICE.',
        '//',
        '// combat/npc_kits.h: GENERATED by tools/schemagen/gen_npc_kits.py from stage 3 combat research (picks.json); do not edit.',
        '#pragma once',
        '',
        '#include <cstddef>',
        '',
        'namespace aoc::worldd::combat::npc_kits {',
        '',
        'struct KitAbility {',
        '    const char* name;',
        '    int         uses;',
        '    int         windup_ms;',
        '    int         range_cm;',
        '};',
        'struct Kit {',
        '    const char*       blueprint;   // the Blueprint class without "_C"',
        '    const KitAbility* abilities;',
        '    size_t            count;',
        '    int               interval_ms;',
        '};',
        '',
    ]
    w = lines.append
    for i, (_, (abilities, _)) in enumerate(kits.items()):
        chunks = [
            ' '.join('{"%s", %d, %d, %d},' % a for a in abilities[j:j + 4])
            for j in range(0, len(abilities), 4)
        ]
        if len(chunks) == 1:
            w('inline constexpr KitAbility kAbilities%d[] = { %s };' % (i, chunks[0]))
        else:
            w('inline constexpr KitAbility kAbilities%d[] = { %s' % (i, chunks[0]))
            for c in chunks[1:-1]:
                w('    ' + c)
            w('    %s };' % chunks[-1])
    w('')
    w('inline constexpr Kit kKits[] = {')
    for i, (leaf, (abilities, interval)) in enumerate(kits.items()):
        w('    {"%s", kAbilities%d, %d, %d},' % (leaf, i, len(abilities), interval))
    w('};')
    w('inline constexpr size_t kKitCount = %d;' % len(kits))
    w('')
    w('}  // namespace aoc::worldd::combat::npc_kits')
    w('')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--picks', default=os.environ.get('AOC_COMBAT_PICKS'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if a.picks:
        with open(a.picks, encoding='utf-8') as f:
            kits = kits_of(json.load(f))
    elif os.path.exists(OUT):
        kits = kits_from_header()
    else:
        print('gen_npc_kits: --picks (or AOC_COMBAT_PICKS) names research/combat/picks.json', file=sys.stderr)
        return 2
    text = render(kits)
    if a.check:
        with open(OUT, encoding='utf-8', newline='') as f:
            have = f.read().replace('\r\n', '\n')
        if have != text:
            print('gen_npc_kits: %s is not what the research gives' % OUT, file=sys.stderr)
            return 1
        print('gen_npc_kits: up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
